class MockVerifier : public ServerAuthVerifier {
  public:
    int chains, sigs;
    MockVerifier() : chains(0), sigs(0) {}
    Error verify_chain(const CertificateChainView& chain, const char* hostname) {
        ++chains;
        return chain.count == 1 && strcmp(hostname, "example.com") == 0 ? XT_OK : XT_ERR_VERIFY;
    }
    Error verify_signature(SignatureScheme scheme, const X509CertificateView& leaf, ByteSpan msg,
                           ByteSpan signature) {
        ++sigs;
        return scheme == SIG_RSA_PSS_RSAE_SHA256 && leaf.public_key_kind == PUBLIC_KEY_RSA &&
                       msg.size == 130 && signature.size == 3
                   ? XT_OK
                   : XT_ERR_VERIFY;
    }
};

int main() {
    int fails = 0;
    X509CertificateView cert;
    Error e = x509_parse_certificate(ByteSpan(cert_der, sizeof(cert_der)), &cert);
    fails += check(e == XT_OK && cert.public_key_kind == PUBLIC_KEY_RSA &&
                       cert.subject_public_key_info.size > 0,
                   "X.509 DER + RSA SPKI parser");
    fails += check(x509_verify_hostname(cert, "example.com") == XT_OK, "X.509 SAN exact hostname");
    fails += check(x509_verify_hostname(cert, "www.example.net") == XT_OK,
                   "X.509 SAN single-label wildcard");
    fails += check(x509_verify_hostname(cert, "a.b.example.net") == XT_ERR_VERIFY,
                   "X.509 wildcard rejects multiple labels");
    fails += check(x509_verify_hostname(cert, "example.org") == XT_ERR_VERIFY,
                   "X.509 SAN mismatch rejected");

    xt_u8 list[1200];
    size_t p = 0;
    size_t n = sizeof(cert_der);
    list[p++] = (xt_u8)(n >> 16);
    list[p++] = (xt_u8)(n >> 8);
    list[p++] = (xt_u8)n;
    memcpy(list + p, cert_der, n);
    p += n;
    list[p++] = 0;
    list[p++] = 0;
    CertificateInfo ci;
    ci.certificate_list = ByteSpan(list, p);
    CertificateChainView cv;
    fails += check(parse_certificate_chain(ci, &cv) == XT_OK && cv.count == 1 &&
                       cv.entries[0].der.size == sizeof(cert_der),
                   "TLS Certificate chain parser");

    xt_u8 th[32];
    memset(th, 0x5a, sizeof(th));
    xt_u8 signedmsg[160];
    size_t written = 0;
    e = build_server_certificate_verify_message(
        ByteSpan(th, 32), MutableByteSpan(signedmsg, sizeof(signedmsg)), &written);
    const char* ctx = "TLS 1.3, server CertificateVerify";
    fails +=
        check(e == XT_OK && written == 130 && signedmsg[0] == 0x20 && signedmsg[63] == 0x20 &&
                  memcmp(signedmsg + 64, ctx, strlen(ctx)) == 0 && signedmsg[64 + strlen(ctx)] == 0,
              "TLS 1.3 CertificateVerify signed input");

    xt_u8 sig[] = {1, 2, 3};
    CertificateVerifyInfo cvi;
    cvi.algorithm = SIG_RSA_PSS_RSAE_SHA256;
    cvi.signature = ByteSpan(sig, 3);
    MockVerifier mv;
    e = authenticate_server_flight(ci, cvi, ByteSpan(th, 32), "example.com", &mv);
    fails += check(e == XT_OK && mv.chains == 1 && mv.sigs == 1,
                   "Server authentication verifier pipeline");
    fails += check(authenticate_server_flight(ci, cvi, ByteSpan(th, 32), "example.com", 0) ==
                       XT_ERR_VERIFY,
                   "Server authentication fails closed without verifier");
    fails += check(authenticate_server_flight(ci, cvi, ByteSpan(th, 32), "wrong.example", &mv) ==
                       XT_ERR_VERIFY,
                   "Server authentication rejects hostname before trust callback");

    // Compact allocation-free trust-store loader.
    xt_u8 store[6 + 3 + sizeof(cert_der)];
    store[0] = 'X';
    store[1] = 'T';
    store[2] = 'S';
    store[3] = '1';
    store[4] = 0;
    store[5] = 1;
    size_t cn = sizeof(cert_der);
    store[6] = (xt_u8)(cn >> 16);
    store[7] = (xt_u8)(cn >> 8);
    store[8] = (xt_u8)cn;
    memcpy(store + 9, cert_der, cn);
    NativeServerAuthVerifier nv(0);
    size_t loaded = 0;
    fails +=
        check(nv.load_trust_store(ByteSpan(store, sizeof(store)), &loaded) == XT_OK && loaded == 1,
              "Compact XTS1 trust-store loader");
    store[0] = 'B';
    fails +=
        check(nv.load_trust_store(ByteSpan(store, sizeof(store)), &loaded) == XT_ERR_BAD_HANDSHAKE,
              "Compact trust-store rejects bad magic");
    store[0] = 'X';

    printf("\n%d failure(s)\n", fails);
    return fails ? 1 : 0;
}
